<#
.SYNOPSIS
    Genererer Mock-klasserne for kodelister (Niras.Jordflytning.IntegrationTests\MockData\Kodelister) fra FlytJordTest.

.DESCRIPTION
    Læser kodelister/referencedata (ingen persondata) og skriver én C#-klasse pr. tabel, som indsætter de samme
    rækker med de samme Id'er i testdatabasen. Kør scriptet igen, hvis en kodeliste ændres i testmiljøet.

.EXAMPLE
    pwsh -ExecutionPolicy Bypass -File Database\FlytJord.Database\Generer-KodelisteMocks.ps1
#>
param(
    [string] $Server = 'info-udv-db01',
    [string] $Database = 'FlytJordTest',
    [pscredential] $Credential,
    [string] $Ud = (Join-Path $PSScriptRoot '..\..\Niras.Jordflytning.IntegrationTests\MockData\Kodelister')
)
$ErrorActionPreference = 'Stop'
if (-not $Credential) {
    $Credential = Get-Credential -Message "SQL-login til $Server/$Database" -UserName 'scripter'
}
$User = $Credential.UserName
$Password = $Credential.GetNetworkCredential().Password

# Tabel -> (WHERE, ORDER BY). Kun kodelister/referencedata - ingen persondata.
$tabeller = [ordered]@{
    'LandsdelType'                      = @('1=1', 'Sortering')
    'JordKlassifikationType'            = @('1=1', 'Sortering, Navn')
    'StatusAnmeldelseType'              = @('1=1', 'Kode')
    'StatusStikproeveType'              = @('1=1', 'Kode')
    'AdvisType'                         = @('1=1', 'Kode')
    'AffaldType'                        = @('1=1', 'Kode')
    'AndenOprindJordType'               = @('1=1', 'Kode')
    'DokumentationType'                 = @('1=1', 'Kode')
    'JordanlaegType'                    = @('1=1', 'Kode')
    'JordflytningType'                  = @('1=1', 'Kode')
    'MiljoeklasseType'                  = @('1=1', 'Kode')
    'OprindelsesstedKlassifikationType' = @('1=1', 'Kode')
    'Kommune'                           = @('1=1', 'Kommunenr')
    'KommuneJordklassifikation'         = @('KommuneId IN (SELECT Id FROM Kommune WHERE Aktiv = 1)', 'KommuneId, JordKlassifikationTypeId')
    'Forureningskomponent'              = @('Id IN (SELECT TOP 5 Id FROM Forureningskomponent WHERE Udloebsdato IS NULL OR Udloebsdato > GETDATE() ORDER BY Sortering, Navn)', 'Sortering, Navn')
    'webpages_Roles'                    = @('1=1', 'RoleId')
}

function CSharp($v, [Type] $t) {
    if ($v -is [DBNull]) { return 'null' }
    switch ($t.Name) {
        'Guid'     { return 'new Guid("' + $v.ToString().ToUpperInvariant() + '")' }
        'Boolean'  { return $(if ($v) { 'true' } else { 'false' }) }
        'Decimal'  { return ([decimal]$v).ToString([Globalization.CultureInfo]::InvariantCulture) + 'm' }
        'Int16'    { return '(short)' + $v }
        'Int32'    { return [string]$v }
        'Int64'    { return [string]$v + 'L' }
        'Byte'     { return '(byte)' + $v }
        'DateTime' { $d = [datetime]$v; return 'new DateTime({0}, {1}, {2})' -f $d.Year, $d.Month, $d.Day }
        'String'   { return '"' + ($v -replace '\\', '\\' -replace '"', '\"' -replace "`r", '' -replace "`n", '\n') + '"' }
        default    { return $null }
    }
}

$cs = "Data Source=$Server;Initial Catalog=$Database;User Id=$User;Password=$Password;Encrypt=True;TrustServerCertificate=True"
$cn = New-Object System.Data.SqlClient.SqlConnection $cs
$cn.Open()
New-Item -ItemType Directory -Force $Ud | Out-Null

foreach ($tabel in $tabeller.Keys) {
    $where, $order = $tabeller[$tabel]
    $cmd = $cn.CreateCommand()
    $cmd.CommandText = "SELECT * FROM dbo.[$tabel] WHERE $where ORDER BY $order"
    $r = $cmd.ExecuteReader()
    $kolonner = 0..($r.FieldCount - 1) | ForEach-Object { [pscustomobject]@{ Navn = $r.GetName($_); Type = $r.GetFieldType($_) } }
    $linjer = New-Object System.Collections.Generic.List[string]
    while ($r.Read()) {
        $felter = foreach ($k in $kolonner) {
            $v = CSharp $r[$k.Navn] $k.Type
            if ($null -ne $v -and $v -ne 'null') { "$($k.Navn) = $v" }
        }
        $linjer.Add("			db.$tabel.Add(new $tabel { " + ($felter -join ', ') + ' });')
    }
    $r.Close()

    $klasse = "${tabel}Mock"
    $indhold = @"
// <auto-generated>
// Genereret fra $Database (kodeliste/referencedata) - samme Id'er og koder som i testmiljøet.
// Ret ikke i hånden; generér igen, hvis kodelisten ændres.
// </auto-generated>
using System;
using Niras.Jordflytning.Core.Models;
using Niras.Jordflytning.IntegrationTests.TestsSetup;

namespace Niras.Jordflytning.IntegrationTests.MockData.Kodelister
{
	public class $klasse : IMockData
	{
		public void Indsaet(JordflytningEntities db)
		{
$($linjer -join "`r`n")
		}
	}
}
"@
    $fil = Join-Path $Ud "$klasse.cs"
    [IO.File]::WriteAllText($fil, ($indhold -replace "(?<!`r)`n", "`r`n"), (New-Object System.Text.UTF8Encoding $true))
    Write-Host ("{0,-40} {1,4} rækker" -f $klasse, $linjer.Count)
}
$cn.Close()
